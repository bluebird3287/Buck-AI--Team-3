// Builds src/data/onlineCourses.ts: which undergraduate Columbus courses had fully online
// (Distance Learning / Distance Enhanced) sections in each term, from OSU Class Search.
// Summer 2026 is the latest published summer, so the planner uses it to pick summer classes
// a student can take online. Independent studies are skipped (they aren't scheduled classes).
// Run with: npm run build:online-courses (refresh when a new summer schedule is published)
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const outFile = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'src', 'data', 'onlineCourses.ts');
const TERMS = [
  { code: '1264', name: 'Summer 2026' },
  { code: '1268', name: 'Autumn 2026' },
  { code: '1272', name: 'Spring 2027' },
];
const MODES = ['dl', 'dh'];
const ONLINE = new Set(['Distance Learning', 'Distance Enhanced']);
const SKIPPED_COMPONENTS = new Set(['Independent Study', 'Field Experience', 'Clinical']);
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

async function fetchPage(term, mode, page) {
  const q = new URLSearchParams({ q: '', campus: 'col', 'academic-career': 'ugrd', term, 'instruction-mode': mode, p: String(page) });
  const res = await fetch(`https://content.osu.edu/v2/classes/search?${q}`, {
    headers: { 'User-Agent': 'BuckAI-Team3 student project (online course data build)' },
  });
  if (!res.ok) throw new Error(`Class search ${term} ${mode} page ${page}: HTTP ${res.status}`);
  return (await res.json()).data;
}

const online = {};
for (const term of TERMS) {
  for (const mode of MODES) {
    for (let page = 1; ; page++) {
      const data = await fetchPage(term.code, mode, page);
      for (const { course, sections } of data.courses) {
        const ok = sections.some((s) => ONLINE.has(s.instructionMode) && !SKIPPED_COMPONENTS.has(s.component) && !s.cancelDate);
        if (!ok) continue;
        const code = `${course.subject} ${course.catalogNumber}`;
        online[code] ??= [];
        if (!online[code].includes(term.name)) online[code].push(term.name);
      }
      console.log(`${term.name} ${mode} page ${page} of ${data.totalPages}`);
      if (page >= data.totalPages || !data.courses.length) break;
      await sleep(300);
    }
  }
}

const sorted = Object.fromEntries(Object.entries(online).sort(([a], [b]) => a.localeCompare(b)));
fs.writeFileSync(
  outFile,
  `// Generated by scripts/build-online-courses.mjs from OSU Class Search. Do not edit by hand.
// Course code -> terms it had a fully online section in.
export const ONLINE_TERMS = ${JSON.stringify(TERMS.map((t) => t.name))};
export const ONLINE_COURSES: Record<string, string[]> = ${JSON.stringify(sorted, null, 1)};
`,
);
console.log(`Wrote ${Object.keys(sorted).length} online courses to src/data/onlineCourses.ts`);
